@dataclass
class WeatherSignal:
    """A trading signal generated by the weather strategy."""

    token_id: str
    direction: str  # "BUY" or "SELL"
    max_price: float
    size: float  # USDC
    edge: float
    model_prob: float
    market_implied: float
    confidence: float
    lead_days: int
    bucket_label: str = ""
    market_id: str = ""
    simulated: bool = False  # True if generated in dry-run mode

    # Pipeline trace — for debugging and monitoring
    bma_mean_f: float = 0.0
    bma_std_f: float = 0.0
    bma_model_count: int = 0
    microclimate_total_f: float = 0.0
    cloud_correction_f: float = 0.0
    metar_temp_f: float | None = None
    metar_locked: bool = False
    conformal_lower_f: float = 0.0
    conformal_upper_f: float = 0.0


@dataclass
class ConformalInterval:
    """Conformal prediction interval for a temperature distribution."""

    center_f: float
    lower_f: float
    upper_f: float
    significance: float  # e.g., 0.1 for 90% interval
    confidence: float  # 1 - significance


