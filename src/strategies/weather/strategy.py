    async def initialize(self) -> None:
        """Initialize all sub-components."""
        self._openmeteo = get_openmeteo_client()
        await self._openmeteo.initialize()

        self._calibrator = TemperatureCalibrator(self._openmeteo)
        self._parser = WeatherMarketParser()
        self._kelly = KellySizer(
            kelly_fraction=self._kelly_fraction_val,
            max_capital_fraction=0.25,
        )

        # Initialize enhanced components
        if self._bma_enabled:
            self._bma_engine = BMAEnsembleEngine(
                openmeteo=self._openmeteo,
                training_window_days=self._bma_window,
            )
            logger.info("bma_engine_initialized", window_days=self._bma_window)

        if self._metar_enabled:
            self._metar_feed = MetarFeed(
                cache_ttl=getattr(get_config().strategy_weather, "metar_cache_ttl_sec", 300),
            )
            logger.info("metar_feed_initialized")

        if self._microclimate_enabled:
            self._microclimate = MicroclimateCorrector()
            logger.info("microclimate_corrector_initialized")

        if self._satellite_enabled:
            self._satellite = SatelliteCorrector(openmeteo=self._openmeteo)
            logger.info("satellite_corrector_initialized")

        await super().initialize()

    async def shutdown(self) -> None:
        """Clean up resources."""
        if self._openmeteo is not None:
            await self._openmeteo.close()
        if self._metar_feed is not None:
            await self._metar_feed.close()
        await super().shutdown()

