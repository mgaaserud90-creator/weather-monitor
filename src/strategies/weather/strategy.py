"""
Weather Calibration Strategy — Enhanced Multi-Model Ensemble Pipeline.

Uses Bayesian Model Averaging (BMA) over 6+ NWP models, real-time METAR
observations, microclimate corrections (UHI, marine layer, elevation, snow
albedo), satellite cloud cover adjustments, and conformal prediction for
calibrated probability intervals.

Pipeline:
  1. BMA Multi-Model Ensemble (ECMWF, GFS, ICON, GEM, UKMO, JMA, HRRR, AIFS)
  2. Station Bias Correction (seasonal, 30-day rolling residuals)
  3. Lead-Time Uncertainty Scaling (σ +0.3°C/day)
  4. Microclimate Corrections (UHI, marine, elevation, snow albedo)
  5. Satellite Cloud Cover Correction (GOES-16/18 proxy via Open-Meteo)
  6. METAR T+0 Lock (if today's max already observed → lock prediction)
  7. Conformal Prediction for Calibrated Intervals
  8. Kelly Criterion Position Sizing

Target: 85-92% win rate, Sharpe ~2.8-3.5 (up from 73-83%, ~1.7).
"""

