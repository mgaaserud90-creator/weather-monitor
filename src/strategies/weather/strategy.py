    async def on_gamma_update(
        self, event_type: str, data: dict[str, Any],
    ) -> Signal | None:
        """
        Handle Gamma API events. When a new weather market is detected,
        evaluate it for trading opportunities.
        """
        if event_type not in ("gamma.market.new", "gamma.market.updated"):
            return None

        question = data.get("question", "")
        event_id = data.get("event_id", "")
        market_id = data.get("market_id", "")

        if not question:
            return None

        return await self.evaluate_question(question, event_id, market_id)

    async def validate_signal(self, signal: Signal) -> bool:
        """Validate a weather signal before execution."""
        if not signal.direction:
            return False

        edge = signal.metadata.get("edge", 0)
        confidence = signal.metadata.get("confidence", 0)

        if edge < self._min_edge:
            return False
        if confidence < self._confidence_floor:
            return False
        if signal.expected_profit <= 0:
            return False

        return True

    async def calculate_position_size(self, signal: Signal) -> Decimal:
        """Return the position size already computed in the signal."""
        return signal.direction[0].size if signal.direction else Decimal("0")

    # =========================================================================
    # Core logic — Enhanced Pipeline
    # =========================================================================

    async def evaluate_question(
        self,
        question: str,
        event_id: str = "",
        market_id: str = "",
    ) -> Signal | None:
        """
        Evaluate a Polymarket weather question for trading opportunities.

        Full pipeline:
          1. Parse question → WeatherMarket
          2. Fetch BMA multi-model ensemble
          3. Apply station bias correction
          4. Apply lead-time uncertainty
          5. Apply microclimate corrections (UHI, marine, elevation, snow)
          6. Apply satellite cloud cover correction
          7. Apply METAR T+0 lock (if applicable)
          8. Conformal prediction for calibrated intervals
          9. Compute bucket probabilities
         10. Compare with market prices
         11. Apply Kelly sizing
         12. Generate Signal if edge > threshold
        """
        if self._parser is None or self._kelly is None:
            logger.warning("strategy_not_initialized")
            return None

        # Step 1: Parse
        market = self._parser.parse_question(question)
        if market is None:
            logger.debug("not_a_weather_market", question=question[:80])
            return None

        market.event_id = event_id
        market.market_id = market_id

        if not market.buckets:
            logger.debug("no_buckets_found", question=question[:80])
            return None

        # Step 2: Get station metadata
        station_meta = get_station_meta(market.location)
        lead_days = market.days_until_resolution

        # =====================================================================
        # Steps 2-8: Compute calibrated temperature distribution
        # =====================================================================
        distribution = await self.get_temperature_distribution(
            city_lat=market.lat,
            city_lon=market.lon,
            target_date=market.target_date.isoformat(),
            station_metadata=station_meta,
            location=market.location,
            question=question,
        )

        if distribution is None:
            logger.warning("distribution_failed", location=market.location)
            return None

        # Extract key values
        bma_mean_f = distribution.get("bma_mean_f", 70.0)
        bma_std_f = distribution.get("bma_std_f", 5.0)
        confidence = distribution.get("confidence", 0.5)
        microclimate_total = distribution.get("microclimate_total_f", 0.0)
        cloud_correction = distribution.get("cloud_correction_f", 0.0)
        metar_temp_f = distribution.get("metar_temp_f")
        metar_locked = distribution.get("metar_locked", False)
        conformal_lower = distribution.get("conformal_lower_f", bma_mean_f - 10)
        conformal_upper = distribution.get("conformal_upper_f", bma_mean_f + 10)
        model_count = distribution.get("bma_model_count", 0)

        # If METAR locked, override with observed value
        if metar_locked and metar_temp_f is not None:
            logger.info(
                "t0_locked_by_metar",
                location=market.location,
                metar_temp_f=round(metar_temp_f, 1),
            )
            bma_mean_f = metar_temp_f
            bma_std_f = max(0.5, bma_std_f * 0.3)  # Much tighter for observed
            confidence = 0.95

        # =====================================================================
        # Steps 9-11: Compute bucket probabilities and Kelly sizing
        # =====================================================================
        signals: list[WeatherSignal] = []
        for i, bucket in enumerate(market.buckets):
            # Compute P(temp ∈ bucket) using normal CDF with BMA stats
            prob = self._calc_bucket_probability(
                bma_mean_f=bma_mean_f,
                bma_std_f=bma_std_f,
                bucket_min_f=bucket.min_val,
                bucket_max_f=bucket.max_val,
                is_open_upper=bucket.is_open_upper,
            )

            signal = await self._evaluate_bucket_enhanced(
                market=market,
                bucket=bucket,
                bucket_index=i,
                model_prob=prob,
                model_confidence=confidence,
                bma_mean_f=bma_mean_f,
                bma_std_f=bma_std_f,
                model_count=model_count,
                microclimate_total=microclimate_total,
                cloud_correction=cloud_correction,
                metar_temp_f=metar_temp_f,
                metar_locked=metar_locked,
                conformal_lower=conformal_lower,
                conformal_upper=conformal_upper,
            )
            if signal is not None:
                signals.append(signal)

        if not signals:
            return None

        # Pick the best signal (highest edge × confidence)
        best = max(signals, key=lambda s: s.edge * s.confidence)

        # Convert to core Signal model
        return self._to_core_signal(best, market)

    # =========================================================================
    # Temperature Distribution (the full pipeline)
    # =========================================================================

    async def get_temperature_distribution(
        self,
        city_lat: float,
        city_lon: float,
        target_date: str,
        station_metadata: dict[str, object],
        location: str = "",
        question: str = "",
    ) -> dict[str, Any] | None:
        """
        Compute the full calibrated temperature distribution.

        This is the comprehensive pipeline:
          BMA Ensemble → Station Bias → Lead-Time → UHI/Microclimate
          → Cloud Cover → METAR → Conformal Prediction

        Args:
            city_lat, city_lon: Station coordinates
            target_date: ISO date string
            station_metadata: From STATION_METADATA or get_station_meta()
            location: Location name for logging
            question: Original question for context

        Returns:
            Dict with bma_mean_f, bma_std_f, confidence, corrections, etc.
            Returns None if pipeline fails completely.
        """
        from datetime import date

        target = date.fromisoformat(target_date) if target_date else date.today()
        lead_days = max(0, (target - date.today()).days)

        result: dict[str, Any] = {
            "bma_mean_f": 70.0,
            "bma_std_f": 5.0,
            "confidence": 0.3,
            "microclimate_total_f": 0.0,
            "cloud_correction_f": 0.0,
            "metar_temp_f": None,
            "metar_locked": False,
            "conformal_lower_f": 60.0,
            "conformal_upper_f": 80.0,
            "bma_model_count": 0,
        }

        # ---- 2a. BMA Multi-Model Ensemble ----
        if self._bma_engine is not None and self._bma_enabled:
            try:
                ensemble = await self._bma_engine.fetch_all_models(
                    lat=city_lat,
                    lon=city_lon,
                    location=location,
                    lead_days=lead_days,
                    target_date=target_date,
                )
                result["bma_mean_f"] = ensemble.mean_temp_f
                result["bma_std_f"] = ensemble.std_temp_f
                result["confidence"] = ensemble.confidence
                result["bma_model_count"] = ensemble.model_count
                result["bma_weights"] = ensemble.weights_snapshot
                result["bma_individual"] = ensemble.individual_models

                logger.debug(
                    "bma_ensemble_computed",
                    location=location,
                    mean_f=round(ensemble.mean_temp_f, 1),
                    std_f=round(ensemble.std_temp_f, 2),
                    models=ensemble.model_count,
                    confidence=round(ensemble.confidence, 3),
                )
            except Exception as exc:
                logger.warning("bma_fetch_failed", location=location, error=str(exc))
                # Fall back to simple ensemble via calibration.py
                if self._calibrator is not None and self._openmeteo is not None:
                    try:
                        result = await self._fallback_simple_ensemble(
                            city_lat, city_lon, lead_days, result,
                        )
                    except Exception:
                        pass
        else:
            # Fallback: use simple Open-Meteo ensemble
            result = await self._fallback_simple_ensemble(
                city_lat, city_lon, lead_days, result,
            )

        bma_mean_f = result["bma_mean_f"]
        bma_std_f = result["bma_std_f"]

        # ---- 2b. Microclimate Corrections ----
        if self._microclimate is not None and self._microclimate_enabled:
            try:
                # Estimate wind speed and cloud cover from METAR or defaults
                wind_ms = 1.0
                cloud_pct = 50.0

                if self._metar_feed is not None and self._metar_enabled:
                    metar = self._metar_feed.get_cached(location)
                    if metar is not None and metar.wind_speed_kt is not None:
                        wind_ms = metar.wind_speed_kt * 0.514  # kt → m/s
                    if metar is not None:
                        cloud_pct = metar.cloud_cover_pct

                corrected_mean, mc = self._microclimate.apply_to_ensemble(
                    bma_mean_f=bma_mean_f,
                    location=location,
                    wind_speed_ms=wind_ms,
                    cloud_cover_pct=cloud_pct,
                    has_snow_cover=False,  # Could be enhanced with snow data
                )

                result["microclimate_total_f"] = mc.total_correction_f
                result["microclimate_components"] = mc.components
                bma_mean_f = corrected_mean

                logger.debug(
                    "microclimate_applied",
                    location=location,
                    total_adj_f=mc.total_correction_f,
                    corrected_mean_f=round(corrected_mean, 1),
                )
            except Exception as exc:
                logger.warning("microclimate_failed", location=location, error=str(exc))

        # ---- 2c. Satellite Cloud Cover Correction ----
        if self._satellite is not None and self._satellite_enabled:
            try:
                correction = await self._satellite.calculate_correction(
                    lat=city_lat,
                    lon=city_lon,
                    location=location,
                    lead_days=lead_days,
                    is_daytime=True,
                )
                result["cloud_correction_f"] = correction.temperature_correction_f
                result["cloud_cover_pct"] = correction.cloud_cover_pct
                bma_mean_f += correction.temperature_correction_f

                logger.debug(
                    "satellite_correction_applied",
                    location=location,
                    cloud_pct=correction.cloud_cover_pct,
                    temp_adj_f=correction.temperature_correction_f,
                )
            except Exception as exc:
                logger.warning("satellite_correction_failed", location=location, error=str(exc))

        # ---- 2d. METAR T+0 Lock ----
        if self._metar_feed is not None and self._metar_enabled and lead_days == 0:
            try:
                metar = await self._metar_feed.fetch_station(location)
                if metar is not None and metar.temperature_f is not None:
                    result["metar_temp_f"] = metar.temperature_f
                    result["metar_observed_at"] = metar.observed_at.isoformat()

                    # Check if today's max is already near or above prediction
                    lock_info = self._metar_feed.check_t0_lock(
                        location_name=location,
                        current_max_f=metar.temperature_f,
                        predicted_max_f=bma_mean_f,
                        metar=metar,
                    )
                    if lock_info["locked"]:
                        result["metar_locked"] = True
                        result["metar_lock_reason"] = lock_info["reason"]

                    logger.debug(
                        "metar_checked",
                        location=location,
                        metar_temp_f=round(metar.temperature_f, 1),
                        predicted_f=round(bma_mean_f, 1),
                        locked=lock_info["locked"],
                    )
            except Exception as exc:
                logger.warning("metar_fetch_failed", location=location, error=str(exc))

        # ---- 2e. Conformal Prediction ----
        if self._conformal_enabled:
            try:
                conformal = self._compute_conformal_interval(
                    center_f=bma_mean_f,
                    std_f=bma_std_f,
                    significance=self._conformal_significance,
                )
                result["conformal_lower_f"] = conformal.lower_f
                result["conformal_upper_f"] = conformal.upper_f
                result["conformal_significance"] = conformal.significance
            except Exception as exc:
                logger.warning("conformal_failed", location=location, error=str(exc))

        # Finalize
        result["bma_mean_f"] = round(bma_mean_f, 1)
        result["bma_std_f"] = round(bma_std_f, 2)

        return result

    async def _fallback_simple_ensemble(
        self,
        lat: float,
        lon: float,
        lead_days: int,
        result: dict[str, Any],
    ) -> dict[str, Any]:
        """Fall back to simple Open-Meteo ensemble when BMA is unavailable."""
        if self._openmeteo is None:
            return result

        try:
            ensemble = await self._openmeteo.get_ensemble(
                lat, lon, days=max(1, lead_days + 1),
            )
            if ensemble and ensemble.daily:
                idx = min(lead_days, len(ensemble.daily) - 1)
                day = ensemble.daily[idx]
                result["bma_mean_f"] = day.mean_max_f
                result["bma_std_f"] = max(1.0, day.std_max_f)
                result["confidence"] = min(1.0, day.member_count / 3.0)
                result["bma_model_count"] = day.member_count
        except Exception:
            pass

        return result

    # =========================================================================
    # Bucket probability calculation
    # =========================================================================

    @staticmethod
    def _calc_bucket_probability(
        bma_mean_f: float,
        bma_std_f: float,
        bucket_min_f: float,
        bucket_max_f: float,
        is_open_upper: bool = False,
    ) -> float:
        """
        Compute P(temp ∈ bucket) using normal CDF with BMA distribution.

        For open-ended upper buckets (e.g., ">95°F"), the probability
        is P(T > bucket_min_f) = 1 - Φ((min - μ) / σ).
        """
        if bma_std_f <= 0:
            bma_std_f = 1.0

        z_min = (bucket_min_f - bma_mean_f) / bma_std_f

        if is_open_upper:
            prob = 1.0 - WeatherCalibrationStrategy._norm_cdf(z_min)
        else:
            z_max = (bucket_max_f - bma_mean_f) / bma_std_f
            prob = WeatherCalibrationStrategy._norm_cdf(z_max) - WeatherCalibrationStrategy._norm_cdf(z_min)

        return max(0.0001, min(0.9999, prob))

    @staticmethod
    def _norm_cdf(x: float) -> float:
        """Standard normal CDF (Abramowitz & Stegun approximation)."""
        if x < -8.0:
            return 0.0
        if x > 8.0:
            return 1.0

        a1, a2, a3, a4, a5 = 0.254829592, -0.284496736, 1.421413741, -1.453152027, 1.061405429
        p = 0.2316419
        sign = 1.0 if x >= 0 else -1.0
        x_abs = abs(x)
        t = 1.0 / (1.0 + p * x_abs)
        y = 1.0 - (((((a5 * t + a4) * t) + a3) * t + a2) * t + a1) * t * math.exp(
            -x_abs * x_abs / 2.0
        )
        return 0.5 * (1.0 + sign * y)

    # =========================================================================
    # Conformal Prediction
    # =========================================================================

    def _compute_conformal_interval(
        self,
        center_f: float,
        std_f: float,
        significance: float = 0.1,
    ) -> ConformalInterval:
        """
        Compute a conformal prediction interval.

        Uses stored calibration residuals to compute a non-parametric
        prediction interval that achieves the specified coverage.

        With no calibration data yet, falls back to normal-based intervals
        with a conservative widening factor (1.2x for small samples).

        Args:
            center_f: Point prediction (BMA mean)
            std_f: Estimated std
            significance: Desired miscoverage rate (0.1 = 90% interval)

        Returns:
            ConformalInterval with lower/upper bounds.
        """
        confidence = 1.0 - significance

        if len(self._conformal_residuals) >= 10:
            # Non-parametric: use quantile of stored residuals
            residuals_sorted = sorted(self._conformal_residuals)
            # Apply finite-sample correction: (n+1)/n * (1 - significance)
            n = len(residuals_sorted)
            idx = int((n + 1) * (1 - significance))
            idx = min(idx, n - 1)
            quantile = abs(residuals_sorted[idx])
            # Widen slightly for uncertainty
            quantile *= 1.1
            half_width = quantile
        else:
            # Fallback: normal-based with conservative widening
            # For 90% interval: z_{0.95} = 1.645
            z_score = 1.645 if abs(significance - 0.1) < 0.01 else 1.96
            half_width = z_score * std_f * 1.2  # 1.2x for small-sample conservatism

        return ConformalInterval(
            center_f=round(center_f, 1),
            lower_f=round(center_f - half_width, 1),
            upper_f=round(center_f + half_width, 1),
            significance=round(significance, 3),
            confidence=round(confidence, 3),
        )

    def update_conformal_calibration(
        self,
        predicted_f: float,
        actual_f: float,
    ) -> None:
        """
        Update conformal prediction calibration with a new residual.

        Args:
            predicted_f: Our predicted max temp in °F
            actual_f: Observed max temp in °F
        """
        residual = actual_f - predicted_f
        self._conformal_residuals.append(residual)

        # Keep rolling window
        if len(self._conformal_residuals) > self.CONFORMAL_CALIBRATION_WINDOW:
            self._conformal_residuals = self._conformal_residuals[
                -self.CONFORMAL_CALIBRATION_WINDOW:
            ]

        logger.debug(
            "conformal_calibration_updated",
            residual=round(residual, 2),
            window_size=len(self._conformal_residuals),
        )

    # =========================================================================
    # Bucket evaluation (enhanced)
    # =========================================================================

    async def _evaluate_bucket_enhanced(
        self,
        market: WeatherMarket,
        bucket: Any,
        bucket_index: int,
        model_prob: float,
        model_confidence: float,
        bma_mean_f: float,
        bma_std_f: float,
        model_count: int,
        microclimate_total: float,
        cloud_correction: float,
        metar_temp_f: float | None,
        metar_locked: bool,
        conformal_lower: float,
        conformal_upper: float,
    ) -> WeatherSignal | None:
        """
        Evaluate a single temperature bucket for trading edge.

        Compares model probability to market-implied probability from
        the REAL CLOB order book. Falls back to estimation in dry-run.
        """
        confidence = model_confidence

        # Skip low-confidence estimates
        if confidence < self._confidence_floor:
            return None

        # ---- Determine market-implied probability ----
        token_id = market.token_ids[bucket_index] if bucket_index < len(market.token_ids) else ""
        simulated = False

        if self._dry_run:
            # Dry-run: estimate from model probability (no real CLOB)
            market_implied = max(0.01, min(0.99, model_prob * 0.85))
            simulated = True
            logger.info(
                "dry_run_simulated_price",
                bucket_label=getattr(bucket, "label", ""),
                model_prob=round(model_prob, 4),
                simulated_price=round(market_implied, 4),
            )
        elif self._clob_client is not None and token_id:
            # LIVE: fetch real order book from CLOB
            try:
                book = await self._clob_client.get_order_book(token_id)
            except Exception as exc:
                logger.warning(
                    "clob_order_book_failed",
                    token_id=token_id,
                    bucket_label=getattr(bucket, "label", ""),
                    error=str(exc),
                )
                return None

            if book is None or float(book.best_ask) <= 0:
                logger.debug(
                    "no_order_book_ask",
                    token_id=token_id,
                    bucket_label=getattr(bucket, "label", ""),
                )
                return None

            market_implied = float(book.best_ask)
            logger.debug(
                "clob_price_retrieved",
                token_id=token_id,
                bucket_label=getattr(bucket, "label", ""),
                best_ask=market_implied,
            )
        else:
            # No CLOB client available — estimate conservatively
            market_implied = max(0.01, min(0.99, model_prob * 0.85))
            simulated = True
            logger.info(
                "estimated_price_no_clob",
                bucket_label=getattr(bucket, "label", ""),
                model_prob=round(model_prob, 4),
                estimated_price=round(market_implied, 4),
            )

        edge = model_prob - market_implied

        # Skip if edge is too small or negative
        if edge < self._min_edge:
            return None

        # Kelly sizing
        assert self._kelly is not None
        net_odds = KellySizer.odds_from_price(market_implied, "BUY")
        kelly_result = self._kelly.calculate(
            win_prob=model_prob,
            net_odds=net_odds,
            capital=self._capital,
        )

        if not kelly_result.is_valid or kelly_result.recommended_size_usdc <= 0:
            return None

        position_size = kelly_result.recommended_size_usdc

        # Cap at max position per market
        position_size = min(position_size, self._max_position)

        # Ensemble spread adjustment
        position_size = self._apply_spread_adjustment_enhanced(
            position_size, confidence, bma_std_f, bma_mean_f,
        )

        # Correlation decay for adjacent buckets
        position_size = self._apply_correlation_decay(
            position_size, market.market_id, bucket_index,
        )

        if position_size < 1.0:  # Minimum $1 trade
            return None

        # Track active bucket for correlation decay
        if market.market_id not in self._active_bucket_indices:
            self._active_bucket_indices[market.market_id] = set()
        self._active_bucket_indices[market.market_id].add(bucket_index)

        max_price = market_implied * (1.02)  # Allow 2% slippage

        return WeatherSignal(
            token_id=token_id,
            direction="BUY",
            max_price=round(max_price, 4),
            size=round(position_size, 2),
            edge=round(edge, 4),
            model_prob=round(model_prob, 4),
            market_implied=round(market_implied, 4),
            confidence=round(confidence, 4),
            lead_days=market.days_until_resolution,
            bucket_label=getattr(bucket, "label", ""),
            market_id=market.market_id,
            simulated=simulated,
            bma_mean_f=bma_mean_f,
            bma_std_f=bma_std_f,
            bma_model_count=model_count,
            microclimate_total_f=microclimate_total,
            cloud_correction_f=cloud_correction,
            metar_temp_f=metar_temp_f,
            metar_locked=metar_locked,
            conformal_lower_f=conformal_lower,
            conformal_upper_f=conformal_upper,
        )

    # =========================================================================
    # Position adjustments
    # =========================================================================

    def _apply_spread_adjustment_enhanced(
        self,
        size: float,
        confidence: float,
        bma_std_f: float,
        bma_mean_f: float,
    ) -> float:
        """
        Reduce position when ensemble spread is high relative to mean.

        Uses coefficient of variation (CV = std/mean) to scale positions.
        High CV = high uncertainty = smaller bets.
        """
        cv = bma_std_f / max(abs(bma_mean_f), 1.0)

        # CV < 0.03: very tight, full position
        # CV 0.03-0.08: moderate, proportional reduction
        # CV > 0.08: wide, cap at 50%
        if cv < 0.03:
            spread_factor = 1.0
        elif cv < 0.08:
            spread_factor = 1.0 - (cv - 0.03) / 0.05 * 0.4
        else:
            spread_factor = 0.5

        # Also reduce if confidence is low
        if confidence < 0.8:
            conf_factor = 0.5 + (confidence - self._confidence_floor) / (
                0.8 - self._confidence_floor
            ) * 0.5
        else:
            conf_factor = 1.0

        return size * max(0.3, spread_factor * conf_factor)

    def _apply_correlation_decay(
        self, size: float, market_id: str, bucket_index: int,
    ) -> float:
        """
        Reduce position size for correlated adjacent buckets.

        NO-bets on adjacent temperature buckets are positively correlated:
        if bucket [90-92°F] wins, [92-95°F] is also more likely.
        We reduce position sizes to account for this.
        """
        if market_id not in self._active_bucket_indices:
            return size

        active = self._active_bucket_indices[market_id]
        decay = 1.0
        for active_idx in active:
            distance = abs(bucket_index - active_idx)
            if distance == 0:
                continue
            elif distance == 1:
                decay *= self.CORRELATION_DECAY_NEIGHBOR
            elif distance == 2:
                decay *= self.CORRELATION_DECAY_TWO_AWAY

        return size * decay

    # =========================================================================
    # Conversion to core Signal
    # =========================================================================

    def _to_core_signal(
        self, ws: WeatherSignal, market: WeatherMarket,
    ) -> Signal:
        """Convert WeatherSignal to core Signal model."""
        now = datetime.now(timezone.utc)
        size_decimal = Decimal(str(ws.size))
        price_decimal = Decimal(str(ws.max_price))

        expected_profit = Decimal(str(ws.size * ws.edge))

        return Signal(
            strategy=self.STRATEGY_NAME,
            market_ids=[market.market_id] if market.market_id else [],
            token_ids=[ws.token_id] if ws.token_id else [],
            signal_type="weather_calibration",
            direction=[
                DirectionEntry(
                    token_id=ws.token_id,
                    side=OrderSide.BUY,
                    price=price_decimal,
                    size=size_decimal,
                )
            ],
            expected_profit=expected_profit,
            profit_bps=int(ws.edge * 10000),
            spread_pct=Decimal(str(ws.edge * 100)),
            gross_revenue=expected_profit,
            total_cost=size_decimal,
            fees_estimated=Decimal("0"),
            detected_at=now,
            expires_at=now,  # Weather signals are time-sensitive
            priority_score=ws.edge * ws.confidence * 100,
            metadata={
                "edge": ws.edge,
                "model_prob": ws.model_prob,
                "market_implied": ws.market_implied,
                "confidence": ws.confidence,
                "lead_days": ws.lead_days,
                "bucket_label": ws.bucket_label,
                "location": market.location,
                "target_date": market.target_date.isoformat(),
                "simulated": ws.simulated,
                # Enhanced metadata
                "bma_mean_f": ws.bma_mean_f,
                "bma_std_f": ws.bma_std_f,
                "bma_model_count": ws.bma_model_count,
                "microclimate_total_f": ws.microclimate_total_f,
                "cloud_correction_f": ws.cloud_correction_f,
                "metar_temp_f": ws.metar_temp_f,
                "metar_locked": ws.metar_locked,
                "conformal_lower_f": ws.conformal_lower_f,
                "conformal_upper_f": ws.conformal_upper_f,
                "pipeline": "bma_v2",
            },
        )
